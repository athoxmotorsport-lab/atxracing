const assert=require('node:assert/strict');
const fs=require('node:fs');
const {stripTypeScriptTypes}=require('node:module');
const source=fs.readFileSync('supabase/functions/public-leaderboard/index.ts','utf8');
const start=source.indexOf('const eventRow =');
const end=source.indexOf('const canonicalCircuitKey =');
const code=stripTypeScriptTypes(source.slice(start,end),{mode:'strip'});
const classify=new Function(code+';return raceCategory')();
assert.equal(classify({competition_code:'ATXS',title_fr:'Sprint régulier'}),'ATXS');
assert.equal(classify({server_name:'ATXS | Barcelona'}),'ATXS');
assert.equal(classify({title_fr:'BALLADE ATX Monza'}),'DR');
assert.equal(classify({competition_code:'BATX'}),'DR');
assert.equal(classify({competition_code:'WGT',title_fr:'Ballade ATX'}),'WGT');
assert.equal(classify({server_name:'WGT | Silverstone'}),'WGT');
assert.equal(classify({server_name:'DR | Monza'}),'DR');
assert.equal(classify({server_name:'Open Lobby'}),'OL');
console.log('PASS: explicit category precedence, ATXS separation, legacy Balade mapped to DR, WGT and open lobby preserved');
const admin=fs.readFileSync('supabase/functions/atx-event-admin/index.ts','utf8');
const validation=stripTypeScriptTypes(admin.slice(admin.indexOf('const clean='),admin.indexOf('async function simgridApi')),{mode:'strip'});
const validate=new Function('simgridUrl',validation+';return validateDraft')(url=>url);
assert.equal(validate({competition:'ATXS',format:'ATXS',raceMinutes:45}).competition,'ATXS');
assert.throws(()=>validate({competition:'ATXS',format:'DR'}),/invalid_format/);
console.log('PASS: admin accepts ATXS and rejects mixed competition/format');
